"""Choose the sealed test set: stratified by answer kind, deterministic for a given seed."""

from __future__ import annotations

import random
from collections import defaultdict
from datetime import date

import yaml

from .loader import SPLIT_FILE, Content, LabeledAnswer
from .models import AnswerKind, Split


def choose_sealed(answers: list[LabeledAnswer], size: int, seed: int) -> list[str]:
    """Round-robin across answer kinds so the sealed set has every kind in similar numbers.

    Within a kind, prefer scenarios that have contributed fewest sealed answers so far,
    so no single scenario dominates the test set.
    """
    if size > len(answers):
        raise ValueError(f"asked for {size} sealed answers but only {len(answers)} exist")
    rng = random.Random(seed)
    by_kind: dict[AnswerKind, list[LabeledAnswer]] = defaultdict(list)
    for la in sorted(answers, key=lambda la: la.key):
        by_kind[la.answer.kind].append(la)
    for group in by_kind.values():
        rng.shuffle(group)

    kinds = [k for k in AnswerKind if by_kind[k]]
    rng.shuffle(kinds)
    per_scenario: dict[str, int] = defaultdict(int)
    chosen: list[str] = []
    while len(chosen) < size:
        for kind in kinds:
            group = by_kind[kind]
            if not group or len(chosen) == size:
                continue
            # Stable min keeps the shuffled order as the tie-breaker.
            pick = min(group, key=lambda la: per_scenario[la.scenario.id])
            group.remove(pick)
            per_scenario[pick.scenario.id] += 1
            chosen.append(pick.key)
    return sorted(chosen)


def write_split(content: Content, size: int, seed: int, force: bool = False) -> Split:
    path = content.root / SPLIT_FILE
    if path.exists() and not force:
        raise FileExistsError(
            f"{SPLIT_FILE} already exists. Re-sealing changes which answers count as unseen; "
            "pass --force only if you have not tuned anything against the dev set yet."
        )
    split = Split(
        seed=seed,
        created=date.today().isoformat(),
        sealed=choose_sealed(content.all_answers(), size, seed),
    )
    header = (
        "# Sealed test set. Do not read, tune prompts against, or debug with these answers.\n"
        "# They are only for the final reported metrics. Generated by `patternly seal`.\n"
    )
    path.write_text(header + yaml.safe_dump(split.model_dump(), sort_keys=False), encoding="utf-8")
    return split
